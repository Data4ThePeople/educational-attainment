"""Pay tables behind FINDINGS.md, recomputed in Python from the data built
into dist/index.html (so they also check the page's own math).

Writes data/clean/pay_tables.md and data/clean/pay_change.csv. Run after
build_viz.py.
"""
import json
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from mapping import GROUPS, GROUP_NAMES, ROOT  # noqa: E402

CLEAN = ROOT / "data" / "clean"
Z90 = 1.645
OUT = []


def table(df):
    OUT.append("| " + " | ".join(map(str, df.columns)) + " |")
    OUT.append("|" + "---|" * len(df.columns))
    for _, r in df.iterrows():
        OUT.append("| " + " | ".join(f"{v:.2f}" if isinstance(v, (float, np.floating)) else str(v) for v in r) + " |")


def main():
    html = (ROOT / "dist" / "index.html").read_text()
    data = json.loads(re.search(r"const DATA = (\{.*?\});\n", html).group(1))
    geo = json.loads(re.search(r"const GEO = (\{.*?\});\n", html).group(1))
    first, last = str(data["first"]), str(data["last"])
    f = data["cpi"][last] / data["cpi"][first]
    n = int(last) - int(first)
    level_of = {x["id"]: lvl for lvl in ("state", "county", "cbsa") for x in geo[lvl]}

    def cagr(a, b):
        return 100 * ((b / a) ** (1 / n) - 1)

    def index(e, w):
        v = sum(w[2 + 2 * i] / w[0] * e[2 + 2 * i] for i in range(len(GROUPS)))
        m = np.sqrt(sum((w[2 + 2 * i] / w[0] * e[3 + 2 * i]) ** 2 for i in range(len(GROUPS))))
        return v, m

    def row(a):
        e1 = [x * f for x in a["e"][first]]
        e2 = a["e"][last]
        w1, w2 = a["v"][first], a["v"][last]
        r = {"geoid": a["id"], "name": a["n"], "level": level_of.get(a["id"], "us")}
        for i, g in enumerate(["all"] + GROUPS):
            p1, m1, p2, m2 = e1[2 * i], e1[2 * i + 1], e2[2 * i], e2[2 * i + 1]
            r[f"{g}_{last}"] = p2
            r[f"{g}_cagr"] = cagr(p1, p2)
            r[f"{g}_sig"] = abs(p2 - p1) / np.sqrt((m1 / Z90) ** 2 + (m2 / Z90) ** 2) > Z90
        (h1, hm1), (h2, hm2), (o2, _) = index(e1, w1), index(e2, w1), index(e2, w2)
        rr = h2 / h1
        r["held_cagr"] = cagr(h1, h2)
        r["held_sig"] = abs(rr - 1) / (np.sqrt(hm2 ** 2 + rr ** 2 * hm1 ** 2) / h1 / Z90) > Z90
        r["own_cagr"] = cagr(h1, o2)
        r["mix_part"] = r["own_cagr"] - r["held_cagr"]
        return r

    us = row({"id": "0100000US", "n": "United States", "c": True, "v": data["us"], "e": data["usPay"]})
    rows = [row(a) for a in data["areas"] if a["c"] and "e" in a and first in a["e"] and last in a["e"]]
    df = pd.DataFrame(rows)
    df.to_csv(CLEAN / "pay_change.csv", index=False, float_format="%.4f")

    OUT.extend(["# Pay tables (generated by scripts/pay_findings.py)", "",
                f"R-CPI-U-RS {first} to {last}: prices up {100 * (f - 1):.1f}%. Yearly change is the compound annual "
                f"growth rate over {n} years, after inflation.", "", "## Nation", ""])
    nat = [{"measure": "Median, all workers", f"{last} ($)": round(us[f"all_{last}"]), "yearly change (%)": us["all_cagr"]}]
    for g in GROUPS:
        nat.append({"measure": f"Median, {GROUP_NAMES[g]}", f"{last} ($)": round(us[f"{g}_{last}"]), "yearly change (%)": us[f"{g}_cagr"]})
    nat += [{"measure": "Index, each year's own education mix", f"{last} ($)": "", "yearly change (%)": us["own_cagr"]},
            {"measure": f"Index, education held at {first} mix", f"{last} ($)": "", "yearly change (%)": us["held_cagr"]},
            {"measure": "Education mix part (points a year)", f"{last} ($)": "", "yearly change (%)": us["mix_part"]}]
    table(pd.DataFrame(nat))

    OUT.extend(["", "## By level: comparable areas", ""])
    t = []
    for lvl, d in df.groupby("level"):
        t.append({"level": lvl, "areas": len(d),
                  "median all-worker change (%/yr)": d.all_cagr.median(),
                  "median held-mix change (%/yr)": d.held_cagr.median(),
                  "median mix part (pts/yr)": d.mix_part.median(),
                  "mix part above 0": int((d.mix_part > 0).sum()),
                  "all-worker rise passes": int((d.all_sig & (d.all_cagr > 0)).sum()),
                  "all-worker fall passes": int((d.all_sig & (d.all_cagr < 0)).sum()),
                  "held-mix rise passes": int((d.held_sig & (d.held_cagr > 0)).sum()),
                  "held-mix fall passes": int((d.held_sig & (d.held_cagr < 0)).sum())})
    table(pd.DataFrame(t))

    OUT.extend(["", "## By level: median yearly change in each group's median pay (%)", ""])
    t = [{"level": lvl, **{GROUP_NAMES[g]: d[f"{g}_cagr"].median() for g in GROUPS}} for lvl, d in df.groupby("level")]
    table(pd.DataFrame(t))

    m = df[df.level == "cbsa"]
    for title, d in [("Metro and micro areas: largest education mix part", m.nlargest(10, "mix_part")),
                     ("Metro and micro areas: held-mix pay rose most (passes the test)", m[m.held_sig].nlargest(10, "held_cagr")),
                     ("Metro and micro areas: held-mix pay fell most (passes the test)", m[m.held_sig].nsmallest(10, "held_cagr"))]:
        OUT.extend(["", f"## {title}", ""])
        table(d[["name", "all_cagr", "held_cagr", "mix_part"]])

    (CLEAN / "pay_tables.md").write_text("\n".join(OUT) + "\n")
    print("\n".join(OUT))


if __name__ == "__main__":
    main()
